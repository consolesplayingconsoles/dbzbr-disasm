#!/usr/bin/env python3
"""List the fighters' full-screen pictures as rebuild BLOCKS, each stream checked first.

    picture_blocks.py <rom> tools/picture_blocks_list.py

PICTURE_TABLE (facts.py) holds one 28-byte record per fighter 1-10 (the reader at $04EA14 takes
P1_Fighter - 1; fighter 0 has its own table, PICTURE_TABLE_0): for each of two pictures (index $EA2E),
an LZSS art stream (to VRAM tile 0), an LZSS plane A map and an optional plane B map (to RAM,
then copied into the nametables), and a palette word. Every stream is decoded here (tools/lzss.py)
and listed only if it decodes, the art to whole tiles. A stream two fighters share is listed once,
under the first. Writes addresses and names only, no game bytes.
"""
import os, struct, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import facts, lzss

d = bytearray(open(sys.argv[1], 'rb').read())
NAMES = ['sangoku', 'sangohan', 'piccolo', 'vegeta', 'trunks', 'cell', 'c18', 'kurilin', 'freezer',
         'likum', 'giniou']
out, seen = [], set()
for r in range(10):
    rec = facts.PICTURE_TABLE + 28 * r
    who = NAMES[r + 1]
    for k in range(2):
        for off, role in ((0, 'art'), (8, 'plane_a'), (16, 'plane_b')):
            p = struct.unpack_from('>I', d, rec + off + 4 * k)[0]
            if p == 0 or p in seen:
                continue
            assert 0x200 <= p < len(d), '%s picture %d %s: %X is not in the ROM' % (who, k, role, p)
            tiles, end = lzss.decode(d, p)
            assert role != 'art' or len(tiles) % 32 == 0, '%s art at %X is not whole tiles' % (who, p)
            seen.add(p)
            out.append((p, end - 1, '%s_picture%d_%s' % (who, k, role), 'lzss'))
# Fighter 0: two 14-byte records at PICTURE_TABLE_0 ([art][plane A][plane B] longs, a palette
# word), picked by $FE03 / 2 instead of the picture index.
for k in range(2):
    rec = facts.PICTURE_TABLE_0 + 14 * k
    for off, role in ((0, 'art'), (4, 'plane_a'), (8, 'plane_b')):
        p = struct.unpack_from('>I', d, rec + off)[0]
        if p == 0 or p in seen:
            continue
        tiles, end = lzss.decode(d, p)
        assert role != 'art' or len(tiles) % 32 == 0, 'sangoku art at %X is not whole tiles' % p
        seen.add(p)
        out.append((p, end - 1, 'sangoku_picture%d_%s' % (k, role), 'lzss'))
out.sort()
for a, b in zip(out, out[1:]):
    assert a[1] < b[0], 'streams overlap: %s and %s' % (a[2], b[2])
with open(sys.argv[2], 'w') as w:
    w.write('# Generated by tools/picture_blocks.py: the fighters\' pictures as rebuild BLOCKS\n'
            '# (start, end inclusive, name, format). Addresses and names only.\n'
            'PICTURE_BLOCKS = [\n')
    for s, e, n, fm in out:
        w.write('    (0x%06X, 0x%06X, %r, %r),\n' % (s, e, n, fm))
    w.write(']\n')
print('%d streams, %d bytes' % (len(out), sum(e - s + 1 for s, e, _, _ in out)))
